function getLang(){ return localStorage.getItem('tv_lang') || (navigator.language||'en').slice(0,2) || 'en'; }
function setLang(l){ localStorage.setItem('tv_lang', l); applyI18n(); }
function t(key){ const lang=getLang(); return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key; }

function applyI18n(){
  const lang = getLang();
  const dict = I18N[lang] || I18N.en;
  const dir = dict._dir || 'ltr';
  document.documentElement.setAttribute('dir', dir);
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key = el.getAttribute('data-i18n-ph');
    if(dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  // update lang selector label
  document.querySelectorAll('.lang-current').forEach(el=>{
    el.textContent = dict._flag + ' ' + lang.toUpperCase();
  });
}

function buildLangSelector(){
  const lang = getLang();
  const cur = I18N[lang] || I18N.en;
  return `<div class="lang-selector-wrap" style="position:relative">
    <button class="selector lang-current" onclick="toggleLangMenu(event)">${cur._flag} ${lang.toUpperCase()} ▾</button>
    <div class="lang-menu" style="display:none;position:absolute;top:44px;right:0;background:var(--card);border:1px solid var(--border-2);border-radius:12px;box-shadow:var(--shadow);padding:6px;z-index:300;min-width:160px">
      ${Object.entries(I18N).map(([code,d])=>`<button onclick="setLang('${code}');toggleLangMenu(event)" style="display:flex;gap:10px;width:100%;padding:9px 12px;border-radius:8px;font-weight:600;color:var(--text-2);font-size:.88rem;${code===lang?'background:var(--chip);color:var(--accent)':''}">${d._flag} ${d._name}</button>`).join('')}
    </div>
  </div>`;
}
function toggleLangMenu(e){
  e && e.stopPropagation();
  const menu = document.querySelector('.lang-menu');
  if(menu) menu.style.display = menu.style.display==='none'?'block':'none';
}
document.addEventListener('click', e=>{
  if(!e.target.closest('.lang-selector-wrap')){ const m=document.querySelector('.lang-menu'); if(m) m.style.display='none'; }
});
document.addEventListener('DOMContentLoaded', applyI18n);
